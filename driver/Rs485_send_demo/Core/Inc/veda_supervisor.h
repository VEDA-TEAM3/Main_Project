/**
 * @file veda_supervisor.h
 * @brief 감시 태스크의 본체. 통신에는 관여하지 않고 상태만 밖으로 드러낸다.
 *
 * CubeMX 가 만드는 `StartDefaultTask()` 의 몸통이 여기로 나와 있다. main.c 쪽에는
 * USER CODE 블록 안의 호출 한 줄만 남는다 -- 그래야 .ioc 로 코드를 다시 생성해도
 * 이 코드가 지워지지 않는다.
 *
 * ### 하는 일 세 가지
 *  1. **LD2 점멸** -- 하행이 살아있으면 빠르게(0.5s), 조용하면 느리게(2s).
 *     USB 없이도 링크 상태를 눈으로 구분할 수 있게 하기 위한 것이다.
 *  2. **USART2(ST-Link VCP)로 진단 카운터 주기 출력** (`[stat]` / `[stack]`).
 *     하행이 바이너리가 되면서 USART6는 사람이 읽을 수 없게 됐고, 프레임이 버려질 때
 *     Master는 밖에서 볼 흔적을 남기지 않는다.
 *  3. **MASTER_SELFTEST_ENABLED 일 때** 순서표대로 위험 이벤트를 스스로 큐에 넣는다.
 *
 * LD2와 huart2를 이 태스크만 만진다. 여러 태스크가 나눠 쓰면 그때부터 보호가 필요해지는데,
 * 진단 수단 때문에 실시간 경로에 락을 들이는 것은 순서가 뒤바뀐 일이다.
 *
 * ### 부팅 배너
 * RPi와 반드시 일치해야 하는 설정을 그대로 찍는다 -- 이 세 줄이 어긋난 채로 하루를
 * 태우는 일이 없도록. `=== VEDA MASTER READY ===` 로 시작하므로, COM 포트를 훑어 어느
 * 것이 Master 인지 찾을 때의 표지이기도 하다.
 *
 * ### 시각 비교에 `(now - target) < 0x80000000U` 를 쓰는 이유
 * 틱이 감겨도(49.7일) 안전한 부호 없는 비교다. `now >= target` 으로 쓰면 감김 직후
 * 조건이 뒤집혀 로그가 49일간 멈춘다.
 *
 * ### 자체 테스트 순서표 (MASTER_SELFTEST_ENABLED)
 * 4개 채널을 순서대로 하나씩 켜고 끈다. 주기(3초)마다 한 단계씩 진행하고 끝에서 처음으로
 * 돌아간다. 한 바퀴는 12단계 = 36초다.
 *
 * 전 채널을 도는 이유: channel_index 는 슬레이브 번호가 아니라 채널 번호다.
 * CHANNELS_PER_SLAVE=2 이므로 index 0,1 은 둘 다 Slave #1 로 가고 index 2,3 이 Slave #2 로
 * 간다. 앞의 두 개만 넣어두면 Slave #2 로 구운 보드는 순서표 전체를 OTHER_SLAVE 로 버려서
 * "테스트를 돌렸는데 아무 일도 안 일어난다"가 된다. 어느 번호로 구운 보드가 꽂혀 있어도
 * 반드시 한 번은 반응하도록 4채널을 모두 돈다.
 *
 * ```
 *   index 0 -> S1:CH1     index 1 -> S1:CH2
 *   index 2 -> S2:CH3     index 3 -> S2:CH4
 * ```
 *
 * 채널마다 WARNING -> DANGER -> NONE 을 한 주기씩 보낸다. 어느 채널에서 불이 들어오는지
 * 눈으로 셀 수 있고, 동시에 Slave 줄 조명의 노랑/빨강/초록이 모두 나오는지 확인된다 --
 * 회선 규약이 등급을 그대로 싣게 바뀌었으므로 WARNING 단계가 DANGER 와 다른 색을 내야 한다.
 *
 * 주입은 **실제 하행 경로와 같은 큐**로 넣는다. ctrl_task 이후는 운영 경로와 완전히 동일하다.
 * 지금 어느 채널을 미는지 `[selftest]` 로 밝히는 이유: 이게 없으면 경광등만 보고 있게 되어,
 * 불이 안 들어올 때 "이 보드가 담당하지 않는 채널이라 정상적으로 무시한 것"과 "받아야 하는데
 * 못 받은 것"을 구분할 수 없다. Slave의 USART2 로그(RX ... -> 판정)와 나란히 놓고 볼 것.
 */

