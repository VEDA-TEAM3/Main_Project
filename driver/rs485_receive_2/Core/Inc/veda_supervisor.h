/**
 * @file veda_supervisor.h
 * @brief 이 보드의 단 하나뿐인 태스크. 부팅 배너부터 메인 루프까지 전부 여기 있다.
 *
 * CubeMX 가 만드는 `StartDefaultTask()` 의 몸통이 여기로 나와 있다. main.c 쪽에는
 * USER CODE 블록 안의 호출 한 줄만 남는다 -- 그래야 .ioc 로 코드를 다시 생성해도
 * 이 코드가 지워지지 않는다.
 *
 * ### 부팅 순서 (순서가 곧 이유다)
 * 1. **LD2 를 MY_SLAVE_ID 번 깜빡인다.** 이 보드가 몇 번으로 구워졌는지 스스로 밝힌다.
 *    USB를 연결하지 않아도 보드만 보고 번호를 셀 수 있다. 릴레이(PA0)는 건드리지 않는다.
 * 2. **부팅 배너.** 담당 채널과 그 출력 핀을 표에서 그대로 뽑아 찍는다. 채널 수를 늘려도
 *    배너는 손댈 필요가 없고, 배선이 어긋났을 때 보드가 스스로 뭘 담당하는지 밝혀 준다.
 *    표의 채널이 담당 범위(MY_FIRST_CHANNEL ~ MY_LAST_CHANNEL)를 벗어나면 `!!OUT-OF-RANGE`
 *    를 붙인다 -- 조용히 두면 "경광등 두 개가 같이 울린다" 로만 드러나 원인 찾기가 어렵다.
 *    부저 극성과 스트립 길이도 함께 찍는다(부팅하자마자 계속 울리면 배선이 아니라 극성
 *    설정이 뒤집힌 것이고, 줄 끝이 어두우면 픽셀 수부터 의심할 것).
 * 3. **줄 조명 초기화 + 초록 점등.** 명령이 오기 전에도 색이 들어오므로, 이것만 보고
 *    "보드가 살아 있고 스트립 배선도 맞다"를 알 수 있다. 수신을 열기 전에 끝낸다 --
 *    첫 프레임 처리와 송신이 겹치지 않게 하기 위해서다.
 *    `neopixel_init()` 이 지금 실패할 수 있는 원인은 타이머 클럭이 84MHz 가 아닌 것뿐이다
 *    (드라이버가 비트 폭을 틱 수로 고정하고 있어 확인 후 거절한다). 조용히 넘기면
 *    "줄 조명만 안 켜진다"로 보여 배선부터 뒤지게 되므로 배너에 남긴다.
 * 4. **DE 를 수신 상태로.** 수신을 열기 전에 불러야 첫 명령을 놓치지 않는다.
 * 5. **인터럽트 수신 개방.** 이후 재무장은 각 콜백이 담당한다.
 *
 * ### 메인 루프의 순서도 이유가 있다
 * ```
 * ACK 송신  ->  수신 로그 출력  ->  줄 조명 갱신  ->  재동기화 검사  ->  루프 계측  ->  osDelay(10)
 * ```
 * ACK 가 맨 앞이다. Master 는 이 응답을 타임아웃(100ms) 안에 받아야 적용을 확인할 수 있어서,
 * 뒤로 밀면 그만큼 왕복 지연이 커진다. 줄 조명 송신(블로킹 0.9ms)을 ACK 뒤에 둔 것도 같은
 * 이유다.
 *
 * **링크가 끊겨도 출력을 건드리지 않는다** -- 마지막 상태를 그대로 유지한다(fail-loud).
 * 정책 설명은 veda_config.h 에 있다.
 */

#ifndef VEDA_SUPERVISOR_H
#define VEDA_SUPERVISOR_H

/**
 * @brief 부팅 절차를 끝내고 메인 루프로 들어간다. StartDefaultTask() 에서 한 번 부르고
 *        돌아오지 않는다.
 */
void veda_supervisor_run(void);

#endif /* VEDA_SUPERVISOR_H */
